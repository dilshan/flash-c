"""Generates docs/LIBRARY.md: for every public header the functions it declares and the library module (source file)
that implements each of them.  Usage: python3 tools/gen_libdoc.py > docs/LIBRARY.md"""
import re, glob, os
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
inc = os.path.join(root, 'runtime', 'include')
mods = {}
for kind, d in (('c0', ''), ('libc', 'c'), ('libm', 'm')):
    for f in sorted(glob.glob(os.path.join(root, 'runtime', 'lib', d, '*.c')) if d else [os.path.join(root, 'runtime', 'lib', 'c0.c')]):
        t = open(f).read()
        t = re.sub(r'/\*.*?\*/', '', t, flags=re.S)
        for m in re.finditer(r'^[A-Za-z_][\w\s\*]*?\b(_?[A-Za-z]\w*)\s*\([^;{]*\)\s*\{', t, re.M):
            mods.setdefault(m.group(1), ('start-up (c0)' if kind == 'c0' else '%s/%s' % (kind, os.path.basename(f)[:-2])))
        for m in re.finditer(r'^[A-Za-z_][\w\s\*\[\]]*?\b(_?[A-Za-z]\w*)\s*(\[[^\]]*\])?\s*(=[^;]*)?;', t, re.M):
            mods.setdefault(m.group(1), ('start-up (c0)' if kind == 'c0' else '%s/%s' % (kind, os.path.basename(f)[:-2])))
out = ['# Flash C run-time library', '',
       'Generated by `tools/gen_libdoc.py`. Every function below is declared in the named header and implemented in the',
       'named module under `runtime/lib/` (`libc/x` = `runtime/lib/c/x.c`, `libm/x` = `runtime/lib/m/x.c`).', '']
for h in sorted(glob.glob(inc + '/*.h') + glob.glob(inc + '/sys/*.h')):
    name = h[len(inc) + 1:]
    if os.path.basename(name).startswith('_'): continue
    t = open(h).read()
    t = re.sub(r'/\*.*?\*/', '', t, flags=re.S)
    funcs = []
    for m in re.finditer(r'^[A-Za-z_][\w\s\*]*?\b(_?[A-Za-z]\w*)\s*\(([^;{}]*)\)\s*;', t, re.M):
        n = m.group(1)
        if n.startswith('__') or n in [x[0] for x in funcs] or m.group(0).lstrip().startswith('typedef'): continue
        funcs.append((n, ' '.join(m.group(0).split())))
    macros = sorted({m.group(1) for m in re.finditer(r'^#define\s+([A-Za-z]\w*)\(', t, re.M) if not m.group(1).startswith('_')})
    if not funcs and not macros: continue
    out.append('## `<%s>`' % name); out.append('')
    if funcs:
        out.append('| Function | Module |'); out.append('|---|---|')
        for n, p in funcs:
            out.append('| `%s` | %s |' % (p.replace('|', '\\|'), mods.get(n, '*(macro or header only)*')))
        out.append('')
    if macros: out.append('Macros: ' + ', '.join('`%s`' % m for m in macros)); out.append('')
print('\n'.join(out))
