"""Generates docs/LIBRARY.md: for every public header the functions it declares and the library module (source file)
that implements each of them.  Usage: python3 tools/gen_libdoc.py > docs/LIBRARY.md"""
import re, glob, os
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
inc = os.path.join(root, 'runtime', 'include')
mods = {}
for kind, d in (('c0', ''), ('libc', 'c'), ('libm', 'm')):
    for f in sorted(glob.glob(os.path.join(root, 'runtime', 'lib', d, '*.c')) if d else [os.path.join(root, 'runtime', 'lib', 'c0.c')]):
        t = open(f).read()
        t = re.sub(r'/\*.*?\*/', '', t, flags=re.S)
        for m in re.finditer(r'^[A-Za-z_][\w\s\*]*?\b(_?[A-Za-z]\w*)\s*\([^;{]*\)\s*\{', t, re.M):
            mods.setdefault(m.group(1), ('start-up (c0)' if kind == 'c0' else '%s/%s' % (kind, os.path.basename(f)[:-2])))
        for m in re.finditer(r'^[A-Za-z_][\w\s\*\[\]]*?\b(_?[A-Za-z]\w*)\s*(\[[^\]]*\])?\s*(=[^;]*)?;', t, re.M):
            mods.setdefault(m.group(1), ('start-up (c0)' if kind == 'c0' else '%s/%s' % (kind, os.path.basename(f)[:-2])))
intro = [
    '# Flash C library reference', '',
    'Every header of the run-time library, the functions it declares and the module that implements each of them.',
    '[Back to the README](../README.md) · See also: [Compiler reference](COMPILER.md#7-the-run-time-library-and-linking)', '',
    '*This file is generated by `tools/gen_libdoc.py`; do not edit it by hand.*', '',
    '## How to read this page', '',
    '* Each section is a header you `#include`. The table lists the declarations in that header.',
    '* **Module** is the library source file that implements the function: `libc/x` is `runtime/lib/c/x.c`,',
    '  `libm/x` is `runtime/lib/m/x.c`, and `start-up (c0)` is `runtime/lib/c0.c`. Functions marked *(macro or header only)*',
    '  have no module of their own.',
    '* Only the functions your program uses are linked into the executable.',
    '* For a description, the arguments, the return value and an example of any function, press **Ctrl+F1** on its name',
    '  in the IDE editor, or look it up in the online help.', '']
out = []
heads = []
for h in sorted(glob.glob(inc + '/*.h') + glob.glob(inc + '/sys/*.h')):
    name = h[len(inc) + 1:]
    if os.path.basename(name).startswith('_'): continue
    t = open(h).read()
    t = re.sub(r'/\*.*?\*/', '', t, flags=re.S)
    funcs = []
    for m in re.finditer(r'^[A-Za-z_][\w\s\*]*?\b(_?[A-Za-z]\w*)\s*\(([^;{}]*)\)\s*;', t, re.M):
        n = m.group(1)
        if n.startswith('__') or n in [x[0] for x in funcs] or m.group(0).lstrip().startswith('typedef'): continue
        funcs.append((n, ' '.join(m.group(0).split())))
    macros = sorted({m.group(1) for m in re.finditer(r'^#define\s+([A-Za-z]\w*)\(', t, re.M) if not m.group(1).startswith('_')})
    if not funcs and not macros: continue
    heads.append(name)
    out.append('## `<%s>`' % name); out.append('')
    if funcs:
        out.append('| Function | Module |'); out.append('|---|---|')
        for n, p in funcs:
            out.append('| `%s` | %s |' % (p.replace('|', '\\|'), mods.get(n, '*(macro or header only)*')))
        out.append('')
    if macros: out.append('Macros: ' + ', '.join('`%s`' % m for m in macros)); out.append('')
def anchor(n):  # GitHub's anchor for the heading "## `<n>`": punctuation is dropped
    return re.sub(r'[^a-z0-9_-]', '', n.lower())
index = ['## Headers', '', ' '.join('[`%s`](#%s)' % (n, anchor(n)) for n in heads), '']
print('\n'.join(intro + index + out))
