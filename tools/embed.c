/* build-time helper: turns text files into C string tables (embedded.c) */
#include <stdio.h>
#include <string.h>
#include <stdlib.h>

static void emit_string(FILE *out, const char *path)
{
    FILE *f = fopen(path, "rb");
    if (!f) { fprintf(stderr, "embed: cannot open %s\n", path); exit(1); }
    int c, col = 0;
    fputs("\"", out);
    while ((c = fgetc(f)) != EOF) {
        if (c == '\n') { fputs("\\n\"\n\"", out); col = 0; continue; }
        if (c == '\\' || c == '"') fputc('\\', out);
        if (c == '\r') continue;
        if (c == '\t') { fputs("\\t", out); continue; }
        if ((unsigned char)c < 32) { fprintf(out, "\\%03o", c); continue; }
        fputc(c, out); col++;
    }
    fputs("\"", out);
    fclose(f);
}

int main(int argc, char **argv)
{
    /* embed <out.c> <runtime.c> <header>... */
    FILE *out = fopen(argv[1], "w");
    if (!out) return 1;
    fputs("/* generated by tools/embed.c - do not edit */\n#include <string.h>\n", out);
    fputs("const char *fc_runtime_source(void) {\n    return ", out);
    emit_string(out, argv[2]);
    fputs(";\n}\n\n", out);
    fputs("static const struct { const char *name, *text; } hdrs[] = {\n", out);
    for (int i = 3; i < argc; i++) {
        const char *base = strrchr(argv[i], '/'); base = base ? base + 1 : argv[i];
        fprintf(out, "    { \"%s\",\n", base);
        emit_string(out, argv[i]);
        fputs("},\n", out);
    }
    fputs("    { 0, 0 }\n};\n\n", out);
    fputs("const char *fc_builtin_header(const char *name) {\n    for (int i = 0; hdrs[i].name; i++) if (!strcmp(hdrs[i].name, name)) return hdrs[i].text;\n    return 0;\n}\n", out);
    fclose(out);
    return 0;
}
