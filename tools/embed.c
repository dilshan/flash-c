/*
 * usage: embed <out.c> kind:path ...
 *   kind  0  start-up module (always linked)             path = runtime/lib/c0.c
 *         1  standard library module                     path = runtime/lib/c/<name>.c
 *         2  math library module                         path = runtime/lib/m/<name>.c
 *         3  optional start-up object (wildargs)         path = runtime/lib/<name>.c
 *         h  public header, name relative to  include/   path = runtime/include/sys/stat.h ->
 * "sys/stat.h" i  internal header used by library modules     path = runtime/lib/_fcrt.h
 */
#include <stdio.h>
#include <string.h>
#include <stdlib.h>

/* Writes the file at path as a C string literal. */
static void emit_string(FILE *out, const char *path)
{
    FILE *f = fopen(path, "rb");
    if (!f) {
        fprintf(stderr, "embed: cannot open %s\n", path);
        exit(1);
    }
    int c;
    fputs("\"", out);
    while ((c = fgetc(f)) != EOF) {
        if (c == '\n') {
            fputs("\\n\"\n\"", out);
            continue;
        }
        if (c == '\\' || c == '"') {
            fputc('\\', out);
        }
        if (c == '\r') {
            continue;
        }
        if (c == '\t') {
            fputs("\\t", out);
            continue;
        }
        if ((unsigned char)c < 32) {
            fprintf(out, "\\%03o", c);
            continue;
        }
        fputc(c, out);
    }
    fputs("\"", out);
    fclose(f);
}

/* Returns the file-name part of a path. */
static const char *base_of(const char *p)
{
    const char *b = strrchr(p, '/');
    return b ? b + 1 : p;
}

/* Generates embedded.c from the run-time library sources and headers (see the Makefile). */
int main(int argc, char **argv)
{
    FILE *out = fopen(argv[1], "w");
    if (!out) {
        return 1;
    }
    fputs("/* generated by tools/embed.c - do not edit */\n#include <string.h>\n#include "
          "\"fci.h\"\n\n",
          out);

    fputs("const FcLibModule fc_lib_modules[] = {\n", out);
    for (int i = 2; i < argc; i++) {
        char kind = argv[i][0];
        if (kind < '0' || kind > '3' || argv[i][1] != ':') {
            continue;
        }
        const char *path = argv[i] + 2;
        char name[64];
        snprintf(name, sizeof name, "%s", base_of(path));
        char *dot = strrchr(name, '.');
        if (dot) {
            *dot = 0;
        }
        fprintf(out, "    { '%c', \"%s\",\n", kind, name);
        emit_string(out, path);
        fputs("},\n", out);
    }
    fputs("    { 0, 0, 0 }\n};\n\n", out);

    fputs("static const struct { const char *name, *text; } hdrs[] = {\n", out);
    for (int i = 2; i < argc; i++) {
        char kind = argv[i][0];
        if ((kind != 'h' && kind != 'i') || argv[i][1] != ':') {
            continue;
        }
        const char *path = argv[i] + 2, *name;
        const char *inc = strstr(path, "/include/");
        name = (kind == 'h' && inc) ? inc + 9 : base_of(path);
        fprintf(out, "    { \"%s\",\n", name);
        emit_string(out, path);
        fputs("},\n", out);
    }
    fputs("    { 0, 0 }\n};\n\n", out);
    fputs("const char *fc_builtin_header(const char *name) {\n    for (int i = 0; hdrs[i].name; "
          "i++) if (!strcmp(hdrs[i].name, name)) return hdrs[i].text;\n    return 0;\n}\n",
          out);
    fputs("int fc_builtin_header_count(void) { int n = 0; while (hdrs[n].name) n++; return n; }\n",
          out);
    fputs("const char *fc_builtin_header_at(int i, const char **text) { if (text) *text = "
          "hdrs[i].text; return hdrs[i].name; }\n",
          out);
    fclose(out);
    return 0;
}
